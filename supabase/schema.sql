-- ---------- Settings: checked, merged on the server ------------------------------
create or replace function public.check_settings(p jsonb) returns void
language plpgsql immutable set search_path = public as $$
begin
  if jsonb_typeof(p) is distinct from 'object'
     or exists (select 1 from jsonb_object_keys(p) k
                 where k not in ('name', 'address', 'phone', 'currencySymbol', 'receiptWidth', 'roundOff', 'printLogo', 'lastBackupAt', 'logoDataUrl'))
     or jsonb_typeof(p -> 'name') is distinct from 'string' or char_length(p ->> 'name') not between 1 and 80
     or (p ? 'address' and (jsonb_typeof(p -> 'address') <> 'string' or char_length(p ->> 'address') > 200))
     or (p ? 'phone' and (jsonb_typeof(p -> 'phone') <> 'string' or char_length(p ->> 'phone') > 20))
     or jsonb_typeof(p -> 'currencySymbol') is distinct from 'string' or char_length(p ->> 'currencySymbol') not between 1 and 3
     or coalesce(p ->> 'receiptWidth', '') not in ('58', '80', 'A4')
     or jsonb_typeof(p -> 'roundOff') is distinct from 'boolean'
     or (p ? 'printLogo' and jsonb_typeof(p -> 'printLogo') <> 'boolean')
     or (p ? 'lastBackupAt' and jsonb_typeof(p -> 'lastBackupAt') <> 'number')
     or (p ? 'logoDataUrl' and (jsonb_typeof(p -> 'logoDataUrl') <> 'string'
         or (p ->> 'logoDataUrl') !~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$'
         or char_length(p ->> 'logoDataUrl') > 700000)) then -- same limit as the app
    raise exception 'Invalid settings' using errcode = 'P0001';
  end if;
end $$;

-- Change some settings (p_set) and remove others (p_unset, e.g. the logo), in one step,
-- so two phones editing different settings at the same time don't undo each other.
create or replace function public.patch_settings(p_set jsonb, p_unset text[] default '{}') returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_data jsonb;
begin
  perform public.require_staff();
  if jsonb_typeof(p_set) is distinct from 'object' then
    raise exception 'Invalid settings' using errcode = 'P0001';
  end if;
  perform 1 from public.sync_clock where id = 1 for update;
  select data into v_data from public.settings where id = 1 for update;
  if not found then
    raise exception 'The shared database is not set up yet' using errcode = 'P0001';
  end if;
  v_data := (v_data || p_set) - coalesce(p_unset, '{}');
  perform public.check_settings(v_data);
  update public.settings set data = v_data where id = 1;
  return v_data;
end $$;

-- ---------- pull_changes: everything that changed after rev p_since ----------------
-- STABLE, so every query below sees ONE snapshot: the page and the clock always agree.
create or replace function public.pull_changes(p_since bigint, p_limit integer default 500) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_clock public.sync_clock%rowtype;
  v_limit integer := least(greatest(coalesce(p_limit, 500), 1), 2000);
  v_since bigint := greatest(coalesce(p_since, 0), 0);
  v_out jsonb;
  v_count integer;
  v_last bigint;
begin
  perform public.require_staff();
  select * into v_clock from public.sync_clock where id = 1;
  with changes as (
    (select m.rev, 'menu' as kind, to_jsonb(m) as row from public.menu m where m.rev > v_since order by m.rev limit v_limit)
    union all
    (select l.rev, 'lines', to_jsonb(l) from public.cheesy_lines l where l.rev > v_since order by l.rev limit v_limit)
    union all
    (select s.rev, 'settings', s.data from public.settings s where s.rev > v_since)
    union all
    (select b.rev, 'bills', b.data from public.bills b where b.rev > v_since order by b.rev limit v_limit)
  ), page as (
    select * from changes order by rev limit v_limit
  )
  select count(*), max(rev), jsonb_build_object(
      'menu', coalesce(jsonb_agg(row order by rev) filter (where kind = 'menu'), '[]'),
      'lines', coalesce(jsonb_agg(row order by rev) filter (where kind = 'lines'), '[]'),
      'settings', (array_agg(row) filter (where kind = 'settings'))[1],
      'bills', coalesce(jsonb_agg(row order by rev) filter (where kind = 'bills'), '[]'))
    into v_count, v_last, v_out
    from page;
  return v_out || jsonb_build_object(
    'dbId', v_clock.db_id,
    'ready', exists (select 1 from public.settings),
    'importOpen', v_clock.import_open,
    'more', v_count = v_limit,
    -- Full page: continue after its last row. Otherwise this page holds every change
    -- up to the clock (same snapshot), so the device is now up to date.
    'rev', case when v_count = v_limit then v_last else greatest(v_clock.rev, v_since) end);
end $$;

-- ---------- save_bill: check a bill and give it the next receipt number ----------
-- Money math is the same integer math as src/core/money.ts and totals.ts.
-- Time is the server's clock in India time, so every device agrees on the month.
create or replace function public.save_bill(p_bill jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_now timestamptz := clock_timestamp();
  v_local timestamp := v_now at time zone 'Asia/Kolkata';
  v_month text := to_char(v_local, 'YYYYMM');
  v_item jsonb;
  v_dish public.menu%rowtype;
  v_ids bigint[] := '{}';
  v_items jsonb := '[]';
  v_cats text[] := '{}';
  v_veg boolean := false;
  v_nonveg boolean := false;
  v_qty integer;
  v_sub bigint := 0;
  v_count integer := 0;
  v_disc jsonb := p_bill -> 'discount';
  v_disc_paise bigint;
  v_net bigint;
  v_round integer;
  v_total bigint;
  v_order text := p_bill ->> 'orderType';
  v_pay text := p_bill ->> 'paymentMode';
  v_table text := nullif(btrim(coalesce(p_bill ->> 'tableNo', '')), '');
  v_customer text := nullif(btrim(coalesce(p_bill ->> 'customerName', '')), '');
  v_cheesy text := coalesce(p_bill ->> 'cheesyLine', '');
  v_seq integer;
  v_no text;
  v_bill jsonb;
  v_ref uuid;
begin
  perform public.require_staff();
  if jsonb_typeof(p_bill) is distinct from 'object' or jsonb_typeof(p_bill -> 'items') is distinct from 'array'
     or jsonb_array_length(p_bill -> 'items') not between 1 and 500 then
    raise exception 'Add at least one item' using errcode = 'P0001';
  end if;
  -- Same lock order as every other writer; reading the menu after it sees the latest prices.
  perform 1 from public.sync_clock where id = 1 for update;

  if p_bill ? 'clientRef' then
    if coalesce(p_bill ->> 'clientRef', '') !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
      raise exception 'Invalid bill reference' using errcode = 'P0001';
    end if;
    v_ref := (p_bill ->> 'clientRef')::uuid;
    select data into v_bill from public.bills where client_ref = v_ref;
    if found then
      return v_bill; -- already saved: this is a retry after a lost reply
    end if;
  end if;

  for v_item in select value from jsonb_array_elements(p_bill -> 'items') loop
    if (v_item ->> 'menuId') !~ '^[0-9]{1,15}$' or (v_item ->> 'qty') !~ '^[0-9]{1,3}$' or (v_item ->> 'unitPaise') !~ '^[0-9]{1,9}$' then
      raise exception 'Invalid item in the bill' using errcode = 'P0001';
    end if;
    select * into v_dish from public.menu where id = (v_item ->> 'menuId')::bigint;
    if not found or v_dish.deleted then
      raise exception 'A dish in this bill is no longer on the menu. Please check the bill and save again.' using errcode = 'P0001';
    end if;
    if v_dish.id = any (v_ids) then
      raise exception 'The same dish appears twice in the bill' using errcode = 'P0001';
    end if;
    v_qty := (v_item ->> 'qty')::integer;
    if v_qty not between 1 and 999 then
      raise exception 'Quantity must be a whole number 1–999' using errcode = 'P0001';
    end if;
    if (v_item ->> 'unitPaise')::integer <> v_dish.price_paise then
      raise exception 'The price of % was changed on another device. Please check the bill and save again.', v_dish.name
        using errcode = 'P0001';
    end if;
    v_ids := v_ids || v_dish.id;
    v_sub := v_sub + v_dish.price_paise::bigint * v_qty;
    v_count := v_count + v_qty;
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'menuId', v_dish.id, 'name', v_dish.name, 'category', v_dish.category, 'isVeg', v_dish.is_veg,
      'unitPaise', v_dish.price_paise, 'qty', v_qty, 'linePaise', v_dish.price_paise::bigint * v_qty));
    if not (v_dish.category = any (v_cats)) then v_cats := v_cats || v_dish.category; end if;
    v_veg := v_veg or v_dish.is_veg;
    v_nonveg := v_nonveg or not v_dish.is_veg;
  end loop;

  if v_disc ->> 'kind' = 'flat' and (v_disc ->> 'paise') ~ '^[0-9]{1,12}$' then
    v_disc := jsonb_build_object('kind', 'flat', 'paise', (v_disc ->> 'paise')::bigint);
    v_disc_paise := least((v_disc ->> 'paise')::bigint, v_sub);
  elsif v_disc ->> 'kind' = 'pct' and (v_disc ->> 'bp') ~ '^[0-9]{1,5}$' and (v_disc ->> 'bp')::integer <= 10000 then
    v_disc := jsonb_build_object('kind', 'pct', 'bp', (v_disc ->> 'bp')::integer);
    v_disc_paise := (2 * v_sub * (v_disc ->> 'bp')::bigint + 10000) / 20000; -- half-up
  else
    raise exception 'Invalid discount' using errcode = 'P0001';
  end if;

  v_net := v_sub - v_disc_paise;
  if coalesce(p_bill ->> 'roundOffPaise', '') !~ '^-?[0-9]{1,2}$' then
    raise exception 'Totals do not add up. Please check the bill and save again.' using errcode = 'P0001';
  end if;
  v_round := (p_bill ->> 'roundOffPaise')::integer;
  if v_round <> 0 and v_round <> ((v_net + 50) / 100) * 100 - v_net then -- 0, or rounded to the nearest rupee
    raise exception 'Totals do not add up. Please check the bill and save again.' using errcode = 'P0001';
  end if;
  v_total := v_net + v_round;
  if (p_bill ->> 'totalPaise') is distinct from v_total::text then
    raise exception 'Totals do not add up. Please check the bill and save again.' using errcode = 'P0001';
  end if;

  if v_order is null or v_order not in ('dine-in', 'takeaway', 'delivery') then
    raise exception 'Invalid order type' using errcode = 'P0001';
  end if;
  if v_pay is null or v_pay not in ('cash', 'upi') then
    raise exception 'Invalid payment mode' using errcode = 'P0001';
  end if;
  if v_order <> 'dine-in' then v_table := null; end if;
  if char_length(v_table) > 10 or char_length(v_customer) > 60 or char_length(v_cheesy) > 120 then
    raise exception 'Some text in the bill is too long' using errcode = 'P0001';
  end if;

  insert into public.counters as c (month_key, last) values (v_month, 1)
    on conflict (month_key) do update set last = c.last + 1
    returning c.last into v_seq;
  v_no := 'RCPT-' || v_month || '-' || lpad(v_seq::text, greatest(4, char_length(v_seq::text)), '0');

  v_bill := jsonb_strip_nulls(jsonb_build_object(
    'billNo', v_no,
    'createdAt', floor(extract(epoch from v_now) * 1000)::bigint,
    'monthKey', v_month,
    'hour', extract(hour from v_local)::integer,
    'weekday', extract(dow from v_local)::integer,
    'items', v_items,
    'orderType', v_order,
    'tableNo', v_table,
    'customerName', v_customer,
    'paymentMode', v_pay,
    'discount', v_disc,
    'subtotalPaise', v_sub,
    'discountPaise', v_disc_paise,
    'roundOffPaise', v_round,
    'totalPaise', v_total,
    'itemCount', v_count,
    'categories', to_jsonb(v_cats),
    'hasVeg', v_veg,
    'hasNonVeg', v_nonveg,
    'cheesyLine', v_cheesy,
    'status', 'paid'));
  update public.menu set used_in_bills = true where id = any (v_ids) and not used_in_bills;
  insert into public.bills (bill_no, created_at, month_key, status, data, client_ref)
    values (v_no, (v_bill ->> 'createdAt')::bigint, v_month, 'paid', v_bill, v_ref);
  return v_bill;
end $$;

-- ---------- void_bill: cancel a bill, keeping it for the audit trail ----------------
create or replace function public.void_bill(p_bill_no text, p_reason text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_reason text := btrim(regexp_replace(coalesce(p_reason, ''), '[\x01-\x08\x0b\x0c\x0e-\x1f\x7f]', '', 'g'));
  v_status text;
  v_data jsonb;
begin
  perform public.require_staff();
  if char_length(v_reason) < 3 then
    raise exception 'Please give a reason (at least 3 characters)' using errcode = 'P0001';
  end if;
  if char_length(v_reason) > 200 then
    raise exception 'Reason must be at most 200 characters' using errcode = 'P0001';
  end if;
  perform 1 from public.sync_clock where id = 1 for update;
  select status into v_status from public.bills where bill_no = p_bill_no for update;
  if not found then raise exception 'Bill not found' using errcode = 'P0001'; end if;
  if v_status = 'void' then raise exception 'Bill is already voided' using errcode = 'P0001'; end if;
  update public.bills
     set status = 'void',
         data = data || jsonb_build_object('status', 'void', 'voidReason', v_reason, 'voidedAt', public.now_ms())
   where bill_no = p_bill_no
   returning data into v_data;
  return v_data;
end $$;

-- ---------- One-time move of the first device's data into the shared database -----
-- Allowed only while the shared database is still empty. Bills keep their numbers
-- (INV- or RCPT-). The monthly counters are set first, from the device's own
-- counters, so new bills saved while old ones are still uploading never collide.
create or replace function public.import_device_data(p_menu jsonb, p_lines jsonb, p_settings jsonb, p_counters jsonb)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_staff();
  perform 1 from public.sync_clock where id = 1 for update;
  if exists (select 1 from public.settings) or exists (select 1 from public.menu) or exists (select 1 from public.bills) then
    raise exception 'The shared database is already set up' using errcode = 'P0001';
  end if;
  perform public.check_settings(p_settings);
  insert into public.settings (id, data) values (1, p_settings);
  insert into public.menu (id, name, category, price_paise, is_veg, active, deleted, used_in_bills, created_at, updated_at)
  select (d ->> 'id')::bigint, d ->> 'name', d ->> 'category', (d ->> 'pricePaise')::integer, (d ->> 'isVeg')::boolean,
         coalesce((d ->> 'active')::boolean, true), coalesce((d ->> 'deleted')::boolean, false),
         coalesce((d ->> 'usedInBills')::boolean, false),
         (d ->> 'createdAt')::bigint, (d ->> 'updatedAt')::bigint
    from jsonb_array_elements(p_menu) d;
  perform setval('public.menu_id_seq', coalesce((select max(id) from public.menu), 0) + 1, false);
  delete from public.cheesy_lines;
  insert into public.cheesy_lines (id, text, built_in, active)
  select (l ->> 'id')::bigint, l ->> 'text', coalesce((l ->> 'builtIn')::boolean, false), coalesce((l ->> 'active')::boolean, true)
    from jsonb_array_elements(p_lines) l;
  perform setval('public.cheesy_lines_id_seq', coalesce((select max(id) from public.cheesy_lines), 0) + 1, false);
  insert into public.counters as c (month_key, last)
  select k ->> 'monthKey', (k ->> 'last')::integer from jsonb_array_elements(p_counters) k
  on conflict (month_key) do update set last = greatest(c.last, excluded.last);
  update public.sync_clock set import_open = true where id = 1;
end $$;

create or replace function public.import_bills(p_bills jsonb) returns integer
language plpgsql security definer set search_path = public as $$
declare v_added integer;
begin
  perform public.require_staff();
  perform 1 from public.sync_clock where id = 1 for update;
  if not (select import_open from public.sync_clock where id = 1) then
    raise exception 'Moving old bills is only allowed while setting up the shared database' using errcode = 'P0001';
  end if;
  if jsonb_typeof(p_bills) is distinct from 'array' or jsonb_array_length(p_bills) > 1000 then
    raise exception 'Send at most 1000 bills at a time' using errcode = 'P0001';
  end if;
  insert into public.bills (bill_no, created_at, month_key, status, data)
  select b ->> 'billNo', (b ->> 'createdAt')::bigint, b ->> 'monthKey', b ->> 'status', b
    from jsonb_array_elements(p_bills) b
  on conflict (bill_no) do nothing;
  get diagnostics v_added = row_count;
  insert into public.counters as c (month_key, last) -- belt and braces; normally already set
  select b ->> 'monthKey', max(substring(b ->> 'billNo' from '-([0-9]+)$')::integer)
    from jsonb_array_elements(p_bills) b group by 1
  on conflict (month_key) do update set last = greatest(c.last, excluded.last);
  return v_added;
end $$;

create or replace function public.finish_import() returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_staff();
  perform 1 from public.sync_clock where id = 1 for update;
  update public.sync_clock set import_open = false where id = 1;
end $$;

