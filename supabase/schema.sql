-- =============================================================================
-- Tikka Bites · one shared database for every device (Supabase / Postgres 15+)
--
-- Run it in your Supabase project: SQL Editor → New query → paste → Run.
-- Running it again is safe (it adds what is missing and refreshes the functions),
-- so run it again after every app update that changes this file.
--
-- Security:
--  * Row-level security (RLS) is on for every table. The public key the app
--    ships with can do nothing on its own.
--  * Only accounts on the staff list can read or change anything, even if public
--    sign-ups were left on by mistake. After creating an account under
--    Authentication → Users, give it access here with:
--        select public.allow_staff('counter@example.com');
--  * Bills can't be written directly: save_bill() / void_bill() check every
--    bill against the menu and issue the receipt number.
-- =============================================================================

-- ---------- Change counter ----------------------------------------------------
-- Every change gets the next "rev" number, so a device fetches only what changed
-- since it last looked. Writers take this one row lock first, so revs are issued
-- in commit order (a device never skips a change) and writers never deadlock.
create table if not exists public.sync_clock (
  id smallint primary key default 1 check (id = 1),
  rev bigint not null default 0,
  import_open boolean not null default false,
  db_id uuid not null default gen_random_uuid() -- tells devices if the database was re-created
);
alter table public.sync_clock add column if not exists db_id uuid not null default gen_random_uuid();
insert into public.sync_clock (id) values (1) on conflict (id) do nothing;

create or replace function public.take_clock() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform 1 from public.sync_clock where id = 1 for update;
  return null;
end $$;

create or replace function public.stamp_rev() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.sync_clock set rev = rev + 1 where id = 1 returning rev into new.rev;
  return new;
end $$;

create or replace function public.now_ms() returns bigint
language sql volatile set search_path = public as $$
  select floor(extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

-- ---------- Staff list ------------------------------------------------------------
create table if not exists public.staff (
  user_id uuid primary key,
  email text not null,
  added_at timestamptz not null default now()
);

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid())
$$;

create or replace function public.require_staff() returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_staff() then
    raise exception 'This account is not on the Tikka Bites staff list. Ask the owner to add it.'
      using errcode = '42501';
  end if;
end $$;

-- Owner only (SQL Editor): give / take away access.
create or replace function public.allow_staff(p_email text) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_email text := lower(btrim(p_email));
  v_id uuid;
begin
  select id into v_id from auth.users where lower(email) = v_email;
  if v_id is null then
    raise exception 'No account with email %. Create it first: Authentication → Users → Add user.', v_email;
  end if;
  insert into public.staff (user_id, email) values (v_id, v_email)
    on conflict (user_id) do update set email = excluded.email;
  return 'Staff access given to ' || v_email;
end $$;

create or replace function public.remove_staff(p_email text) returns text
language plpgsql security definer set search_path = public as $$
begin
  delete from public.staff where email = lower(btrim(p_email));
  if not found then return 'Nobody with email ' || lower(btrim(p_email)) || ' was on the staff list'; end if;
  return 'Staff access removed from ' || lower(btrim(p_email)) || ' (they are signed out within an hour)';
end $$;

-- ---------- Tables --------------------------------------------------------------
create table if not exists public.menu (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  category text not null check (char_length(category) between 1 and 30),
  price_paise integer not null check (price_paise between 1 and 10000000),
  is_veg boolean not null,
  active boolean not null default true,
  deleted boolean not null default false, -- soft delete: old bills keep the dish
  used_in_bills boolean not null default false,
  created_at bigint not null default public.now_ms(),
  updated_at bigint not null default public.now_ms(),
  rev bigint not null default 0
);

create table if not exists public.cheesy_lines (
  id bigint generated by default as identity primary key,
  text text not null check (char_length(text) between 1 and 120),
  built_in boolean not null default false,
  active boolean not null default true,
  removed boolean not null default false, -- kept as a marker so other devices learn about deletes
  rev bigint not null default 0
);

create table if not exists public.settings (
  id smallint primary key default 1 check (id = 1),
  data jsonb not null check (jsonb_typeof(data) = 'object' and pg_column_size(data) < 2000000),
  rev bigint not null default 0
);

create table if not exists public.counters (
  month_key text primary key check (month_key ~ '^[0-9]{6}$'),
  last integer not null check (last >= 0)
);

create table if not exists public.bills (
  bill_no text primary key check (bill_no ~ '^(RCPT|INV)-[0-9]{6}-[0-9]{4,}$'),
  created_at bigint not null,
  month_key text not null check (month_key ~ '^[0-9]{6}$'),
  status text not null check (status in ('paid', 'void')),
  data jsonb not null check (jsonb_typeof(data) = 'object'), -- the bill exactly as the app stores it
  created_by uuid default auth.uid(),                          -- which staff account saved it
  rev bigint not null default 0
);

-- A retry of the same save (the reply was lost on a bad connection) carries the same
-- reference, so it gets the bill that was already saved instead of a second receipt.
alter table public.bills add column if not exists client_ref uuid;
create unique index if not exists bills_client_ref on public.bills (client_ref);

create index if not exists menu_rev on public.menu (rev);
create index if not exists cheesy_lines_rev on public.cheesy_lines (rev);
create index if not exists bills_rev on public.bills (rev);
create index if not exists bills_created_at on public.bills (created_at);

