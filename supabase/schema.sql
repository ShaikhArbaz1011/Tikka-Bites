create or replace trigger cheesy_lines_rev before insert or update on public.cheesy_lines for each row execute function public.stamp_rev();
create or replace trigger settings_lock before insert or update on public.settings for each statement execute function public.take_clock();
create or replace trigger settings_rev before insert or update on public.settings for each row execute function public.stamp_rev();
create or replace trigger bills_lock before insert or update on public.bills for each statement execute function public.take_clock();
create or replace trigger bills_rev before insert or update on public.bills for each row execute function public.stamp_rev();

-- The server keeps the "last edited" time, so a device with a wrong clock can't skew it.
create or replace function public.touch_menu() returns trigger
language plpgsql set search_path = public as $$
begin
  if (new.name, new.category, new.price_paise, new.is_veg, new.active, new.deleted)
     is distinct from (old.name, old.category, old.price_paise, old.is_veg, old.active, old.deleted) then
    new.updated_at := public.now_ms();
  end if;
  return new;
end $$;
create or replace trigger menu_touch before update on public.menu for each row execute function public.touch_menu();

